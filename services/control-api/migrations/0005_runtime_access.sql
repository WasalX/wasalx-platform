DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'wasalx_app') THEN
    CREATE ROLE wasalx_app NOLOGIN;
  END IF;
END
$$;

DO $$
BEGIN
  EXECUTE format('GRANT CONNECT ON DATABASE %I TO wasalx_app', current_database());
END
$$;

GRANT USAGE ON SCHEMA public, app TO wasalx_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO wasalx_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO wasalx_app;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA app TO wasalx_app;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO wasalx_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO wasalx_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA app GRANT EXECUTE ON FUNCTIONS TO wasalx_app;
