import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { stripVTControlCharacters } from "node:util";

export function generateBaseline(log) {
  const root = "/home/runner/work/wasalx-platform/wasalx-platform/";
  const jobs = new Map();
  for (const line of log.split(/\r?\n/u)) {
    const [job, , raw] = line.split("\t");
    if (!raw) continue;
    const text = stripVTControlCharacters(raw.replace(/^\uFEFF?\d{4}-\S+Z /u, ""));
    if (!jobs.has(job)) jobs.set(job, []);
    jobs.get(job).push(text);
  }
  const tests = [];
  for (const [job, lines] of jobs) {
    if (!job.startsWith("Unit ")) continue;
    for (let i = 0; i < lines.length; i++) {
      const failure = /^test at (.+):\d+:\d+$/u.exec(lines[i]);
      if (!failure) continue;
      const name = /^✖ (.+) \([\d.]+ms\)$/u.exec(lines[i + 1])?.[1];
      const missing = /open '([^']+)'|directory -- (\S+) \(LoadError\)/u.exec(lines[i + 2]);
      assert(name && missing, "Failure is not a named missing add-on input");
      const input = (missing[1] ?? missing[2]).replace(root, "");
      assert(!input.startsWith("/") && !input.includes(".."));
      const duplicate = tests.some(entry => entry.file === failure[1] && entry.name === name);
      // The harness imports this test, so the corrected run executes it twice.
      const entrypoint = duplicate ? "tests/application-e2e-harness.test.mjs" : failure[1];
      if (duplicate) assert.equal(failure[1], "tests/simulation-native-group.test.mjs");
      tests.push({ file: failure[1], name, entrypoint, input, reason: "needs the add-on source" });
    }
  }
  assert.equal(tests.length, 10, "Expected the approved corrected run's 10 failed executions");
  return {
    sourceRun: "https://github.com/WasalX/wasalx-platform/actions/runs/44043107820",
    sourceHead: "8e07a88bfecd2163a79a8b73f1d2b3c52e033172",
    logSha256: createHash("sha256").update(log).digest("hex"),
    tests,
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const baseline = generateBaseline(readFileSync(process.argv[2], "utf8"));
  writeFileSync(new URL("./hosted-ci-baseline.mjs", import.meta.url),
    '// No entries are added by hand without Portfolio\'s approval.\n'
    + '// Generated by scripts/generate-hosted-ci-baseline.mjs from the source run below.\n'
    + `export default ${JSON.stringify(baseline, null, 2)};\n`);
}
